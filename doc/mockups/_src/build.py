"""Builds the self-contained mockups in doc/mockups/ from this folder:  python doc/mockups/_src/build.py

Each file of VARIANTS here is the body of one design (its own <style>, markup and <script>); base.css and base.js are
inlined into every output file, with the EQ presets read from src/g6_cli/g6_spec/eq_presets.py (the file is parsed,
nothing of g6_cli is imported or run).
"""
import ast
import json
import pathlib
import re

SRC = pathlib.Path(__file__).resolve().parent
OUT = SRC.parent
REPO = OUT.parent.parent
# one design; a tuple so another body can be added beside it
VARIANTS = ('01-sbc-sidebar.html',)


def presets() -> dict:
    tree = ast.parse((REPO / 'src/g6_cli/g6_spec/eq_presets.py').read_text(encoding='utf-8'))
    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and getattr(node.target, 'id', '') == 'EQ_PRESETS':
            return eval(compile(ast.Expression(node.value), 'eq_presets', 'eval'), {'__builtins__': {}})
    raise SystemExit('EQ_PRESETS not found')


def main() -> None:
    css = (SRC / 'base.css').read_text(encoding='utf-8')
    js = (SRC / 'base.js').read_text(encoding='utf-8').replace('/*PRESETS*/{}', json.dumps(presets(), separators=(',', ':')))
    for name in VARIANTS:
        body = (SRC / name).read_text(encoding='utf-8')
        title = re.search(r'<!--\s*title:\s*(.*?)\s*-->', body).group(1)
        html = (f'<!doctype html>\n<html lang="en" data-theme="dark">\n<head>\n<meta charset="utf-8">\n'
                f'<meta name="viewport" content="width=device-width,initial-scale=1">\n<title>{title} · G6 mockup</title>\n'
                f'<!-- Generated by _src/build.py from _src/{name}, base.css and base.js. Edit those, not this file. -->\n'
                f'<style>\n{css}</style>\n</head>\n<body>\n<script>\n{js}</script>\n{body}</body>\n</html>\n')
        (OUT / name).write_text(html, encoding='utf-8', newline='\n')
        print('wrote', name, len(html) // 1024, 'KB')


if __name__ == '__main__':
    main()
