"""
Export language-neutral test vectors from the Python implementation, for the Rust port (doc/rust-port.md).

    python tools/export_vectors.py            # writes.json, effects.json, eq_presets.json (no device needed)
    python tools/export_vectors.py --live     # also status_live.json: a read-only status transcript from a real G6

Files go to tests/vectors/. ``tests/g6_cli/vectors_test.py`` regenerates the offline ones and fails if they drift, so
the vectors always describe what the Python code actually sends.

Nothing here writes to a device: every command runs against a recorder instead of the G6, and --live only replays
the status queries ``read_status`` already sends.
"""
from __future__ import annotations

import argparse
import contextlib
import importlib.util
import io
import json
import sys
from pathlib import Path
from unittest import mock

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))

import g6_cli  # noqa: E402
import g6_cli.g6_api as g6_api  # noqa: E402
from g6_cli.g6_spec import PlaybackFilter  # noqa: E402
from g6_cli.g6_spec.eq_presets import EQ_PRESETS  # noqa: E402
from g6_cli.g6_spec.lighting_effects import (  # noqa: E402
    DEFAULT_PERIOD_S, EFFECTS, LevelFollower, effect_frame, level_to_brightness,
)
from g6_cli.g6_status import DeviceStatus  # noqa: E402

OUT = ROOT / 'tests' / 'vectors'
NOTE = ('Generated by tools/export_vectors.py from the Python implementation; do not edit. '
        'HID reports are the 64-byte payload without the leading report id 0x00, trailing zero bytes removed '
        '(pad to 64). USB Audio Control requests are host-to-device class requests to the interface.')


class Recorder:
    """Stands in for G6Device: records what would be sent."""

    def __init__(self):
        self.hid: list[str] = []
        self.usb: list[dict] = []

    def send_hid_data_to_device(self, hid_data_list):
        for frag in hid_data_list:
            self.hid.append(bytes.fromhex(str(frag)).rstrip(b'\0').hex())

    def send_audio_data_to_device(self, audio_data_list):
        for a in audio_data_list:
            self.usb.append({
                'bmRequestType': a.get_bm_request_type().hex(), 'bRequest': a.get_b_request().hex(),
                'wValue': a.get_w_value().hex(), 'wIndex': a.get_w_index().hex(),
                'wLength': a.get_w_length().hex(), 'data': a.get_data_fragment().hex(),
            })

    def is_hid_interface_available(self):
        return True

    def is_audio_interface_available(self):
        return True

    def claim_audio_interface(self):
        pass

    def release_audio_interface(self):
        pass

    def hid_held_open(self):
        return contextlib.nullcontext()


def _fixed_status(output='Speakers') -> DeviceStatus:
    return DeviceStatus(output=output)


def _cli_cases() -> list[list[str]]:
    """Every CLI case of tests/g6_cli/cli_mock_test.py, plus the newer flags."""
    spec = importlib.util.spec_from_file_location('cli_mock_cases', ROOT / 'tests' / 'g6_cli' / 'cli_mock_test.py')
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    cases = [factory() for name, factory in mod.CLI_CASES if name != 'reload_alsa_and_pipewire']
    cases += [
        ['--sbx', 'Enabled'], ['--sbx', 'Disabled'], ['--scout-mode', 'Enabled'], ['--scout-mode', 'Disabled'],
        ['--eq', 'Enabled'], ['--eq', 'Disabled'], ['--eq-preamp', '-12'], ['--eq-preamp', '3.5'],
        ['--eq-band', '31', '-12'], ['--eq-band', '1k', '2.5'], ['--eq-band', '16k', '12'],
        ['--playback-line-out-headphone-virtualization', 'Enabled'],
        ['--playback-line-out-headphone-virtualization', 'Disabled'],
        ['--lighting-rgb', '255', '0', '0'], ['--lighting-rgb', '17', '34', '51'], ['--lighting-disable'],
        ['--lighting-volume-ring', 'Enabled'], ['--lighting-volume-ring', 'Disabled'],
        ['--scout-mode', 'Enabled', '--sbx', 'Disabled'],  # pins the order writes are applied in
    ]
    for pid in EQ_PRESETS:
        for output in ('Speakers', 'Headphones'):
            cases.append(['--eq-preset', pid, '--eq-preset-output', output])
    for pf in PlaybackFilter:
        cases.append(['--playback-filter', pf.name])
    seen, unique = set(), []
    for c in cases:
        if tuple(c) not in seen:
            seen.add(tuple(c))
            unique.append(c)
    return unique


def record(argv: list[str]) -> dict:
    rec = Recorder()
    with mock.patch.object(g6_api, 'detect_device', return_value=rec), \
            mock.patch.object(g6_cli, 'read_status', return_value=_fixed_status()), \
            mock.patch.object(g6_cli, 'determine_toggle_state', return_value=g6_cli.TOGGLE_STATE_HEADPHONES), \
            mock.patch.object(g6_api.G6Api, 'reload_alsa_and_pipewire',
                              side_effect=AssertionError('never reload audio services here')), \
            contextlib.redirect_stdout(io.StringIO()):
        g6_cli.main(['--dry-run'] + argv)
    entry = {'argv': argv, 'hid': rec.hid}
    if rec.usb:
        entry['usb'] = rec.usb
    return entry


def build_writes() -> dict:
    return {'note': NOTE + " --toggle-output assumes the current output is Headphones (so it switches to Speakers); --eq-preset without --eq-preset-output uses Headphones.",
            'cases': [record(argv) for argv in _cli_cases()]}


def build_effects() -> dict:
    frames = []
    for effect in EFFECTS:
        period = DEFAULT_PERIOD_S[effect]
        for rgb in ((0, 0, 255), None):
            for level in ((None,) if effect != 'music' else (0.0, 0.5, 1.0)):
                for i in range(0, 61, 3):
                    t = i / 30 * period / 2
                    frames.append({'effect': effect, 't': t, 'period': period, 'rgb': rgb, 'level': level,
                                   'frame': list(effect_frame(effect, t, period, rgb, level))})
    levels = [0.0, 1e-9, 10 ** (-45 / 20), 10 ** (-30 / 20), 10 ** (-22.5 / 20), 0.1, 0.5, 1.0, 2.0]
    follower, seq = LevelFollower(), []
    for x in [1.0, 0.0, 0.0, 0.3, 0.0, 0.9, 0.0, 0.0, 0.0, 0.0]:
        seq.append({'level': x, 'dt': 1 / 30, 'out': follower.update(x, 1 / 30)})
    return {
        'note': 'Generated by tools/export_vectors.py; frames are (r, g, b, brightness). Compare floats with 1e-9.',
        'frames': frames,
        'level_to_brightness': [{'peak': p, 'out': level_to_brightness(p)} for p in levels],
        'level_follower': {'decay_s': follower.decay_s, 'steps': seq},
    }


def build_eq_presets() -> dict:
    return {'note': "SoundBlaster Command's G6 EQ presets (see g6_spec/eq_presets.py). "
                    'Values: preamp, then 31 Hz .. 16 kHz, in dB.',
            'presets': {pid: {'speakers': list(sp), 'headphones': list(hp)} for pid, (sp, hp) in EQ_PRESETS.items()}}


def build_status_live() -> dict:
    from g6_cli import g6_status as s
    exchanges = []
    path = s.find_hid_path()
    if path is None:
        raise SystemExit('no G6 found')

    def query(payload: bytes):
        r = s.hid_query(payload, path)
        exchanges.append({'query': payload.hex(), 'response': r.rstrip(b'\0').hex() if r else None})
        return r

    status = s.collect_status(query)
    d = status.to_dict()
    d.pop('mixer', None)  # OS mixer, not HID
    return {'note': 'Read-only HID status transcript from a real G6 (queries in the order collect_status sends '
                    'them; responses without trailing zeros, null = no answer) and what the Python parsers make '
                    'of it. Feed the responses to the Rust parsers and compare.',
            'exchanges': exchanges, 'parsed': d}


def write(name: str, data: dict):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(json.dumps(data, indent=1) + '\n', encoding='utf-8')


OFFLINE = {'writes.json': build_writes, 'effects.json': build_effects, 'eq_presets.json': build_eq_presets}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--live', action='store_true', help='also read a status transcript from the connected G6')
    args = ap.parse_args()
    for name, build in OFFLINE.items():
        write(name, build())
        print('wrote', OUT / name)
    if args.live:
        write('status_live.json', build_status_live())
        print('wrote', OUT / 'status_live.json')


if __name__ == '__main__':
    main()
